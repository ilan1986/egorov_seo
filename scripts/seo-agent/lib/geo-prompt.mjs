// GEO-директивы для промпта генерации статьи — поднимают citability каждой новой статьи.
// Подмешивается в systemPrompt генерации в lib/generate-post.mjs:
//   import { GEO_DIRECTIVES } from './geo-prompt.mjs';
//   const system = BASE_PROMPT + '\n\n' + GEO_DIRECTIVES;
// Приёмы: answer-first, вопросные H2, citation capsules, evidence-triple, таблицы, определения —
// то, что нейросети вырезают в ответ (blog-geo / geo-citability / geo-platform-optimizer).

export const GEO_DIRECTIVES = `
ОПТИМИЗАЦИЯ ПОД ЦИТИРОВАНИЕ НЕЙРОСЕТЯМИ (GEO) — обязательно:
1. TL;DR-бокс в самом верху статьи (до вступления): 40-60 слов, прямой краткий ответ на главный вопрос темы. Именно его модель заберёт в ответ.
2. Answer-first в КАЖДОЙ секции: первое предложение под каждым H2 — прямой законченный ответ (≤35 слов), без «это», «поэтому», «однако» в начале. Развёртка — дальше.
3. 60-70% заголовков H2/H3 формулируй как реальные вопросы пользователя («Что такое…», «Как…», «Сколько…», «Чем… отличается от…»). Бери формулировки из блока PAA (реальные вопросы Яндекса), если он передан.
4. Citation capsule: в каждой секции хотя бы один абзац 40-60 слов, самодостаточный — понятен вне контекста статьи, называет субъект явно (не местоимением).
5. Конкретика вместо воды: цифры, сроки, диапазоны, названия, условия. «Быстро и качественно» → «за 3-5 рабочих дней». Каждый факт проверяем.
6. Evidence-triple на каждую статистику: год в тексте прозы + название источника + (по возможности) уточнение. Не выдумывай цифры — если не уверен, дай диапазон с оговоркой.
7. Определения терминов выделяй жирным и давай паттерном «X — это …» / «Под X понимают …». Это самый цитируемый формат.
8. Минимум одна сравнительная таблица с шапкой (столбцы-критерии) и один маркированный список — готовые блоки для ответа ИИ.
9. Секция «Частые вопросы» в конце: 5-8 пар «вопрос (H3) → ответ 40-60 слов со статистикой». Она же питает FAQPage-schema.
10. Актуальность: указывай текущий год там, где это уместно теме; свежие данные цитируются охотнее.
`.trim();

